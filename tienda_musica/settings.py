def load_local_environment(path):
    if not path.is_file():
        return
    for line_number, line in enumerate(path.read_text(encoding='utf-8-sig').splitlines(), 1):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        name, separator, value = line.partition('=')
        name = name.strip()
        if not separator or not name.isidentifier():
            raise ImproperlyConfigured(f'L?nea {line_number} inv?lida en .env. Usa NOMBRE=valor.')
        os.environ.setdefault(name, value)


def require_env(name, *, allow_empty=False):
    value = os.environ.get(name)
    if value is None or (not allow_empty and not value.strip()):
        raise ImproperlyConfigured(f'Configura {name} en el entorno o en el archivo .env.')
    return value


